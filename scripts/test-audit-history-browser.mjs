import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const base = process.env.DBSCOUT_AUDIT_TEST_URL || 'http://127.0.0.1:1431';
const output = process.env.DBSCOUT_AUDIT_SCREENSHOTS || '/tmp/blackcat-audit-review';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.addInitScript(() => localStorage.setItem("dbscout_language", "zh-CN"));
page.setDefaultTimeout(15000);
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
try {
  await page.goto(base);
  await page.getByRole('button', { name: '展开数据库栏', exact: true }).click();
  await page.getByRole('button', { name: '备份中心', exact: true }).waitFor();
  await page.evaluate(async () => {
    const { mockWorkbenchInvoke: invoke } = await import('/src/workbench/mock/mockBackend.js');
    const { getOrInitRows } = await import('/src/workbench/mock/mockRows.js');
    const rows = structuredClone(getOrInitRows('demo', 'game_db', 'player'));
    const session = await invoke('open_table_session', { connectionId: 'demo', database: 'game_db', tableName: 'player' });
    const sessionId = session.sessionId || session.session_id;
    const changed = rows.map((row) => ({ ...row, level: '77' }));
    await invoke('replace_table_rows', { request: { sessionId, rows: changed, mappedColumns: Object.keys(changed[0]) } });
    await invoke('update_cell', { request: { sessionId, rowIdentity: { id: String(changed[0].id) }, columnName: 'level', oldValue: '77', newValue: '88' } });
    window.auditTestBefore = rows;
  });
  const start = performance.now();
  await page.getByRole('button', { name: '备份中心', exact: true }).click();
  await page.locator('.wb-audit-table').filter({ has: page.locator('strong', { hasText: /^player$/ }) }).click();
  await page.locator('.wb-audit-operation').filter({ has: page.locator('header strong', { hasText: /^导入表$/ }) }).waitFor();
  console.log(`cold navigation: ${Math.round(performance.now() - start)} ms (browser mock)`);
  const imported = page.locator('.wb-audit-operation').filter({ has: page.locator('header strong', { hasText: /^导入表$/ }) });
  await imported.getByRole('button', { name: /查看.*条明细/ }).click();
  await imported.locator('.wb-audit-detail').first().waitFor();
  await page.screenshot({ animations: 'disabled', path: `${output}/desktop-light.png` });
  await imported.getByRole('button', { name: '恢复到此次操作前' }).click();
  await page.locator('.wb-audit-preview').waitFor();
  assert.match(await page.locator('.wb-audit-preview').innerText(), /此节点之后/);
  await page.screenshot({ animations: 'disabled', path: `${output}/restore-preview.png` });
  await page.getByRole('button', { name: '确认恢复此表', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '已恢复到所选操作之前' }).waitFor();
  const restored = await page.evaluate(async () => {
    const { getOrInitRows } = await import('/src/workbench/mock/mockRows.js');
    return JSON.stringify(getOrInitRows('demo', 'game_db', 'player')) === JSON.stringify(window.auditTestBefore);
  });
  assert.equal(restored, true);
  await page.getByRole('button', { name: '关闭备份中心' }).click();
  const warmStart = performance.now();
  await page.getByRole('button', { name: '备份中心', exact: true }).click();
  await page.locator('.wb-audit-table').first().waitFor();
  console.log(`warm reopen: ${Math.round(performance.now() - warmStart)} ms (browser mock)`);
  await page.locator('.wb-audit-table').first().click();
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.waitForFunction(() => document.querySelector('.mysql-workbench')?.dataset.theme === 'dark');
  await page.screenshot({ animations: 'disabled', path: `${output}/desktop-dark.png` });
  await page.locator('.wb-audit-operation').first().getByRole('button', { name: '恢复到此次操作前' }).click();
  await page.locator('.wb-audit-preview').waitFor();
  await page.screenshot({ animations: 'disabled', path: `${output}/restore-preview-dark.png` });
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.setViewportSize({ width: 640, height: 900 });
  await page.getByRole('button', { name: '返回表列表' }).click();
  await page.screenshot({ animations: 'disabled', path: `${output}/narrow-tables.png` });
  await page.locator('.wb-audit-table').first().click();
  await page.screenshot({ animations: 'disabled', path: `${output}/narrow-history.png` });
  const overflow = await page.locator('.wb-backup-dialog').evaluate((el) => el.scrollWidth > el.clientWidth + 1);
  assert.equal(overflow, false);
  await page.getByRole('button', { name: '返回表列表' }).focus();
  await page.keyboard.press('Enter');
  await page.locator('#wb-audit-table-search').waitFor({ state: 'visible' });
  assert.deepEqual(errors, []);
  console.log('Audit history: import + later edit + preview + atomic mock restore + responsive/keyboard checks passed.');
} catch (error) { await page.screenshot({ animations: 'disabled', path: `${output}/failure.png` }); console.log(await page.locator('body').innerText()); throw error; } finally { await browser.close(); }
