import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const base = process.env.DBSCOUT_AUDIT_TEST_URL || 'http://127.0.0.1:1431';
const output = process.env.DBSCOUT_AUDIT_SCREENSHOTS || '/tmp/blackcat-shared-audit-review';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.addInitScript(() => localStorage.setItem('dbscout_language', 'zh-CN'));
page.setDefaultTimeout(15000);
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
try {
  await page.goto(base);
  await page.getByRole('button', { name: '展开数据库栏', exact: true }).click();
  await page.evaluate(async () => {
    const { mockWorkbenchInvoke: invoke } = await import('/src/workbench/mock/mockBackend.js');
    const { getOrInitRows } = await import('/src/workbench/mock/mockRows.js');
    const rows = structuredClone(getOrInitRows('demo', 'game_db', 'player'));
    const session = await invoke('open_table_session', { connectionId: 'demo', database: 'game_db', tableName: 'player' });
    await invoke('update_cell', { request: { sessionId: session.sessionId || session.session_id, rowIdentity: { id: String(rows[0].id) }, columnName: 'level', oldValue: rows[0].level, newValue: '88' } });
  });
  await page.getByRole('button', { name: '备份中心', exact: true }).click();
  await page.locator('.wb-audit-table').first().click();
  const geometry = () => page.locator('.wb-audit-history').evaluate((el) => ({ columns: getComputedStyle(el).gridTemplateColumns, radius: getComputedStyle(el).borderRadius }));
  const localGeometry = await geometry();
  assert.ok(await page.locator('.wb-audit-restore').count());
  await page.getByRole('tab', { name: '设置', exact: true }).click();
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill('shared-ui-test');
  await page.getByRole('textbox', { name: '昵称', exact: true }).fill('共享测试员');
  await page.getByRole('button', { name: '注册', exact: true }).click();
  await page.locator('.wb-account-session').waitFor();
  await page.evaluate(async () => {
    const { mockWorkbenchInvoke: invoke } = await import('/src/workbench/mock/mockBackend.js');
    await invoke('sync_audit_now');
  });
  await page.getByRole('tab', { name: '变更日志', exact: true }).click();
  const start = performance.now();
  await page.getByRole('button', { name: '全员可见', exact: true }).click();
  await page.locator('.wb-audit-table').filter({ hasText: 'player' }).click();
  await page.locator('.wb-audit-operation').first().waitFor();
  console.log(`shared cold selection: ${Math.round(performance.now() - start)} ms (browser mock)`);
  assert.deepEqual(await geometry(), localGeometry);
  assert.equal(await page.locator('.wb-audit-restore').count(), 0);
  assert.equal(await page.locator('.wb-audit-preview').count(), 0);
  assert.match(await page.locator('.wb-audit-heading').innerText(), /不能在此恢复/);
  assert.match(await page.locator('.wb-backup-audit-actor').first().innerText(), /共享测试员/);
  await page.locator('.wb-audit-details-toggle').first().click();
  await page.locator('.wb-audit-detail').first().waitFor();
  await page.screenshot({ animations: 'disabled', path: `${output}/shared-light.png` });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.waitForFunction(() => document.querySelector('.mysql-workbench')?.dataset.theme === 'dark');
  await page.screenshot({ animations: 'disabled', path: `${output}/shared-dark.png` });
  await page.setViewportSize({ width: 640, height: 900 });
  await page.screenshot({ animations: 'disabled', path: `${output}/shared-narrow.png` });
  assert.equal(await page.locator('.wb-backup-dialog').evaluate((el) => el.scrollWidth > el.clientWidth + 1), false);
  await page.getByRole('button', { name: '返回表列表', exact: true }).click();
  await page.locator('#wb-audit-table-search').fill('not-a-table');
  await page.locator('#wb-audit-table-search').press('Enter');
  assert.equal(await page.locator('.wb-audit-table').count(), 0);
  await page.locator('#wb-audit-table-search').fill('player');
  await page.locator('#wb-audit-table-search').press('Enter');
  await page.locator('.wb-audit-table').first().click();
  await page.getByRole('button', { name: '关闭备份中心', exact: true }).click();
  const warm = performance.now();
  await page.getByRole('button', { name: '备份中心', exact: true }).click();
  await page.locator('.wb-audit-table').first().waitFor();
  console.log(`shared warm reopen: ${Math.round(performance.now() - warm)} ms (browser mock)`);
  await page.getByRole('button', { name: '仅本机', exact: true }).click();
  await page.locator('.wb-audit-table').first().click();
  await page.locator('.wb-audit-restore').first().waitFor();
  assert.deepEqual(errors, []);
  console.log('Shared audit: matching geometry, actors, details, read-only, search, theme, narrow layout and local-mode regression passed.');
} catch (error) {
  await page.screenshot({ animations: 'disabled', path: `${output}/failure.png` });
  console.log(await page.locator('body').innerText());
  throw error;
} finally { await browser.close(); }
